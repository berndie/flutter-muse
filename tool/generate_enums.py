#!/usr/bin/env python3
"""Generates the Dart enums of flutter_muse_platform_interface from the jar.

Enums cross the platform channel as their Java ordinal, so the Dart enums
must list their values in exactly the same order as the Java enums. Re-run
this script whenever the Muse SDK is updated:

    python3 tool/generate_enums.py [path/to/libmuse_android.jar]

Without an argument the jar is looked up in $MUSE_SDK_DIR, then in
flutter_muse_android/android/libs/.
"""
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "flutter_muse_platform_interface" / "lib" / "src" / "enums.g.dart"


def find_jar() -> pathlib.Path:
    if len(sys.argv) > 1:
        return pathlib.Path(sys.argv[1])
    if os.environ.get("MUSE_SDK_DIR"):
        return pathlib.Path(os.environ["MUSE_SDK_DIR"]) / "libmuse_android.jar"
    return ROOT / "flutter_muse_android" / "android" / "libs" / "libmuse_android.jar"
PKG = "com.choosemuse.libmuse"

# Public enums of the SDK, in the order they are emitted.
ENUMS = [
    "Accelerometer", "AnnotationFormat", "Battery", "ConnectionState",
    "DrlRef", "Eeg", "ErrorType", "Gyro", "Magnetometer", "MessageType",
    "MuseDataPacketType", "MuseElementsVersion", "MuseModel", "MusePreset",
    "NotchFrequency", "Ppg", "Pressure", "ReaderMusePlaybackSettings",
    "ResultLevel", "Severity", "TimestampMode", "UltraViolet",
]


# Dart names that differ from the Java names, to avoid clashing with
# Flutter (package:flutter/widgets.dart already defines ConnectionState).
RENAMES = {"ConnectionState": "MuseConnectionState"}


def dart_name(java_name: str) -> str:
    parts = java_name.split("_")
    out = parts[0].lower()
    for prev, part in zip(parts, parts[1:]):
        # Keep a separator between two numeric parts (V_2_0 -> v2_0).
        if prev[-1:].isdigit() and part[:1].isdigit():
            out += "_" + part.lower()
        else:
            out += part[:1].upper() + part[1:].lower()
    return out


def main() -> None:
    jar = find_jar()
    if not jar.is_file():
        raise SystemExit(f"jar not found: {jar}")
    javap = subprocess.run(
        ["javap", "-public", "-cp", str(jar)] + [f"{PKG}.{e}" for e in ENUMS],
        check=True, capture_output=True, text=True,
    ).stdout
    blocks = re.split(r"^Compiled from .*$", javap, flags=re.M)
    lines = [
        "// GENERATED by tool/generate_enums.py from libmuse_android.jar.",
        "// Do not edit by hand: values must stay in Java ordinal order.",
        "// ignore_for_file: constant_identifier_names, public_member_api_docs",
        "",
    ]
    found = set()
    for block in blocks:
        m = re.search(rf"Enum<{re.escape(PKG)}\.(\w+)>", block)
        if not m:
            continue
        name = m.group(1)
        values = re.findall(
            rf"public static final {re.escape(PKG)}\.{name} (\w+);", block)
        found.add(name)
        dart_type = RENAMES.get(name, name)
        lines.append(f"/// Mirrors `{PKG}.{name}`.")
        lines.append(f"enum {dart_type} {{")
        for v in values:
            lines.append(f"  /// `{name}.{v}`")
            lines.append(f"  {dart_name(v)},")
        lines.append("}")
        lines.append("")
    missing = set(ENUMS) - found
    if missing:
        raise SystemExit(f"enums not found in jar: {sorted(missing)}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)} ({len(found)} enums)")


if __name__ == "__main__":
    main()
